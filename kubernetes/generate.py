    return {"name": "wait-db", "image": VERSIONS["WAIT_IMAGE"],
            "envFrom": [{"secretRef": {"name": f"{svc}-env"}}],
            "command": ["sh", "-c", 'until nc -z -w 2 "$DB_HOST" "$DB_PORT"; do echo "waiting for $DB_HOST:$DB_PORT"; sleep 2; done']}


