def dump(objs: list[dict], svc: str) -> str:
    return HEADER.format(svc=svc) + "---\n".join(yaml.dump(o, Dumper=_Dumper, sort_keys=False, width=120, allow_unicode=True) for o in objs)


def kustomization(resources: list[str], namespace: str | None = NAMESPACE) -> str:
    k = {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization"}
    if namespace:
        k["namespace"] = namespace
    k["resources"] = resources
    return "# GENERATED by kubernetes/generate.py — do not edit.\n" + yaml.safe_dump(k, sort_keys=False)


def render(out: Path) -> list[str]:
    scope = load_scope()
    ported = scope.get("ported") or []
    prod_only = set(scope.get("prod_only") or [])
    domain = load_env(REPO / ".env").get("DOMAIN") or load_env(REPO / ".env.example").get("DOMAIN", "example.com")
    written = []
    for svc in ported:
        if svc == "shared-postgres":
            files = shared_postgres()
        elif svc == "shared-mariadb":
            files = shared_mariadb()
        elif svc == "nginx-plain":
            files = nginx_plain()
        else:
            files = convert(svc)
            dbo = app_database(svc)
            if dbo and not external_db(svc):
                files["database.yaml"] = dbo
            if svc == "authentik":
                files["middleware.yaml"] = [authentik_middleware()]
        d = out / "apps" / svc
        d.mkdir(parents=True, exist_ok=True)
        for fname, objs in sorted(files.items()):
            (d / fname).write_text(dump(objs, svc))
        (d / "kustomization.yaml").write_text(kustomization(sorted(files)))
        written.append(svc)
        for env, dom in (("test", TEST_DOMAIN), ("prod", domain)):
            if env == "test" and svc in prod_only:
                continue
            ed = out / "envs" / env / svc
            ed.mkdir(parents=True, exist_ok=True)
            res = [f"../../../apps/{svc}"]
            routes = nginx_site_routes(dom) if svc == "nginx-plain" else route_objects(svc, dom)
            if routes:
                (ed / "routes.yaml").write_text(dump(routes, svc))
                res.append("routes.yaml")
            (ed / "kustomization.yaml").write_text(kustomization(res))
    return written


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if kubernetes/generated/ is out of date")
    args = ap.parse_args()
    try:
        with tempfile.TemporaryDirectory() as tmp:
            tmpd = Path(tmp) / "generated"
            render(tmpd)
            if args.check:
                cmp = filecmp.dircmp(tmpd, GENERATED) if GENERATED.is_dir() else None
                stale = _diff(cmp) if cmp else ["(kubernetes/generated/ missing)"]
                if stale:
                    print("kubernetes/generated/ is out of date — run: uv run kubernetes/generate.py\n  " + "\n  ".join(stale))
                    return 1
                print("kubernetes/generated/ is up to date")
                return 0
            if GENERATED.exists():
                shutil.rmtree(GENERATED)
            shutil.copytree(tmpd, GENERATED)
            print(f"wrote {GENERATED.relative_to(REPO)}/")
            return 0
    except GenError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


def _diff(c: filecmp.dircmp, prefix: str = "") -> list[str]:
    out = [f"{prefix}{x} (only in new)" for x in c.left_only] + [f"{prefix}{x} (stale, removed in new)" for x in c.right_only]
    _, mismatch, errors = filecmp.cmpfiles(c.left, c.right, c.common_files, shallow=False)
    out += [f"{prefix}{x} (differs)" for x in mismatch + errors]
    for sub, sc in c.subdirs.items():
        out += _diff(sc, f"{prefix}{sub}/")
    return out


if __name__ == "__main__":
    sys.exit(main())
