# ── localhost ports ───────────────────────────────────────────────────────
NODE_PORT_BASE = 30100
TRAEFIK_NODE_PORTS = {80: 30080, 443: 30443}


PORT_DEFAULT = re.compile(r"\$\{[A-Za-z_][A-Za-z0-9_]*:-(\d+)\}")


def port_default(v) -> str:
    """${GRAFANA_PORT:-8134} -> 8134: Compose's own default (no-interpolate
    keeps the expression; a test checks .env.example agrees)."""
    return PORT_DEFAULT.sub(r"\1", str(v))


def published_ports(s: dict) -> list[tuple[str, int, int, str]]:
    """[(host IP, host port, container port, protocol)] for Compose ports
    bound to a literal address (127.0.0.1 and the 10.8.0.1 VPN mirror);
    ports bound to a ${VAR} address (AdGuard's DNS_BIND_IP) are left out."""
    out = []
    for p in s.get("ports") or []:
        if isinstance(p, dict):
            ip, hp, tgt, proto = p.get("host_ip"), port_default(p.get("published")), p.get("target"), p.get("protocol", "tcp")
        else:
            spec, _, proto = port_default(p).partition("/")
            parts = spec.split(":")
            if len(parts) != 3:
                continue
            ip, hp, tgt, proto = parts[0], parts[1], parts[2], proto or "tcp"
        if ip and hp and re.fullmatch(r"[\d.]+", str(ip)) and str(hp).isdigit():
            out.append((str(ip), int(hp), int(tgt), proto))
    return out


def loopback_ports(s: dict) -> list[tuple[int, int, str]]:
    """[(host port, container port, protocol)] a Compose service publishes on
    127.0.0.1 (compose.prod.yml), long or short (${VAR}) syntax."""
    out = []
    for p in s.get("ports") or []:
        if isinstance(p, dict):
            if p.get("host_ip") == "127.0.0.1" and p.get("published"):
                out.append((int(port_default(p["published"])), int(p["target"]), p.get("protocol", "tcp")))
        else:
            spec, _, proto = port_default(p).partition("/")
            parts = spec.split(":")
            if len(parts) == 3 and parts[0] == "127.0.0.1":
                out.append((int(parts[1]), int(parts[2]), proto or "tcp"))
    return out


def host_ports() -> list[dict]:
    """Every 127.0.0.1 port Compose publishes for a ported service, as a
    kind port mapping: host port -> node port. NodePort Services (fixed node
    ports, in host-port order) carry them to the container; nginx-plain's go
    to Traefik, which does its job here; host-network containers (wg-easy)
    listen on the node directly. kind binds these only at cluster creation."""
    scope = load_scope()
    entries = []
    for svc in scope.get("ported") or []:
        ov_c = load_overrides(svc).get("containers") or {}
        for n, s in (load_compose(svc).get("services") or {}).items():
            c = s.get("container_name") or n
            co = ov_c.get(c) or {}
            if co.get("skip") and svc != "nginx-plain":
                continue
            if s.get("network_mode") == "host":
                for port in co.get("ports") or []:
                    entries.append({"svc": svc, "container": c, "host": int(port), "target": int(port),
                                    "protocol": "tcp", "node": int(port), "direct": True})
                continue
            for host, target, proto in loopback_ports(s):
                e = {"svc": svc, "container": c, "host": host, "target": target, "protocol": proto}
                if svc == "nginx-plain":
                    if target not in TRAEFIK_NODE_PORTS:
                        continue
                    e["node"] = TRAEFIK_NODE_PORTS[target]
                entries.append(e)
    # Node ports are allocated like a lock file: a port keeps the node port
    # the committed generated/host-ports.yaml gives it, so adding a service
    # never renumbers the others (kind binds its mappings at creation, so a
    # renumbered Service would no longer match them). New ports get the
    # lowest free number.
    lock = {}
    lf = GENERATED / "host-ports.yaml"
    if lf.is_file():
        lock = {(e["host"], e["protocol"]): e["node"] for e in (yaml.safe_load(lf.read_text()) or [])}
    used = {e["node"] for e in entries if "node" in e}
    for e in entries:
        n = lock.get((e["host"], e["protocol"]))
        if "node" not in e and n and n >= NODE_PORT_BASE and n not in used:
            e["node"] = n
            used.add(n)
    nxt = NODE_PORT_BASE
    for e in sorted(entries, key=lambda e: (e["host"], e["protocol"])):
        if "node" not in e:
            while nxt in used:
                nxt += 1
            e["node"] = nxt
            used.add(nxt)
    return sorted(entries, key=lambda e: (e["host"], e["protocol"]))


LOCAL_ACCESS_NS = "local-access"
LOCAL_ACCESS_HEALTH_PORT = 8399
TRAEFIK_BACKENDS = {80: "traefik.infra.svc.cluster.local:80", 443: "traefik.infra.svc.cluster.local:443"}


def local_access() -> dict[str, list[dict]]:
    """Compose's published ports (127.0.0.1:<port>, and the 10.8.0.1 VPN
    mirror) served by ONE proxy in its own namespace, instead of a hostPort
    on every app: apps can then meet Pod Security Baseline, which forbids
    hostPort. nginx's stream module forwards each port at the TCP level (web,
    SSH, TLS alike) to the app's Service, resolving names per connection so
    services that aren't running don't stop the proxy. On a cluster on this
    machine its hostPorts bind the same addresses as Compose; on kind, its
    NodePort Service carries the lock-file node ports (host-ports.yaml)."""
    entries = host_ports()
    listen, maps, ports, nodeports = [], [], [], []
    seen = set()
    for svc in load_scope().get("ported") or []:
        compose = load_compose(svc)
        for n, s in (compose.get("services") or {}).items():
            c = re.sub(r"[^a-z0-9-]", "-", (s.get("container_name") or n).lower())
            for ip, hp, tgt, proto in published_ports(s):
                backend = (TRAEFIK_BACKENDS.get(tgt) if svc == "nginx-plain"
                           else f"{c}.{NAMESPACE}.svc.cluster.local:{tgt}")
                if not backend:
                    continue
                if (hp, proto) not in seen:
                    seen.add((hp, proto))
                    listen.append(f"        listen {hp}{' udp' if proto == 'udp' else ''};")
                    maps.append(f"        {hp} {backend};")
                ports.append({"containerPort": hp, "hostPort": hp, "hostIP": ip,
                              **({"protocol": "UDP"} if proto == "udp" else {})})
    for e in entries:
        # nginx-plain's ports are Traefik's own node ports (kind maps them
        # straight there); the proxy holding one too broke Traefik's Service
        # ("provided port is already allocated", 2026-10-04).
        if e["node"] >= NODE_PORT_BASE and not e.get("direct") and e["svc"] != "nginx-plain":
            nodeports.append({"name": f"h{e['host']}", "port": e["host"], "targetPort": e["host"],
                              "nodePort": e["node"], "protocol": e["protocol"].upper()})
    conf = "\n".join([
        "# GENERATED by kubernetes/generate.py (local_access): Compose's published ports.",
        "worker_processes 1;",
        "events { worker_connections 4096; }",
        "http {",
        f"    server {{ listen {LOCAL_ACCESS_HEALTH_PORT}; location = /_health {{ access_log off; return 200 \"ok\\n\"; }} }}",
        "}",
        "stream {",
        "    resolver kube-dns.kube-system.svc.cluster.local valid=10s ipv6=off;",
        "    map $server_port $backend {",
        *maps,
        "    }",
        "    server {",
        *listen,
        "        proxy_pass $backend;",
        "        proxy_timeout 1h;",
        "    }",
        "}",
        ""])
    labels = {"app.kubernetes.io/part-of": "homeserver", "app.kubernetes.io/name": "local-access"}
    cm = {"nginx.conf": conf}
    nginx_image = next(iter(load_compose("nginx-plain")["services"].values()))["image"]
    container = harden_container({
        "name": "local-access", "image": nginx_image, "ports": ports,
        "readinessProbe": {"httpGet": {"path": "/_health", "port": LOCAL_ACCESS_HEALTH_PORT}, "periodSeconds": 10},
        "livenessProbe": {"httpGet": {"path": "/_health", "port": LOCAL_ACCESS_HEALTH_PORT}, "periodSeconds": 10,
                          "failureThreshold": 6},
        "volumeMounts": [{"name": "conf", "mountPath": "/etc/nginx/nginx.conf", "subPath": "nginx.conf", "readOnly": True}],
    }, {})
    return {
        "namespace.yaml": [{"apiVersion": "v1", "kind": "Namespace",
                            "metadata": {"name": LOCAL_ACCESS_NS, "labels": {
                                # hostPort is a Baseline violation by design here: this is
                                # the one place that holds them (docs/17 "Localhost ports").
                                "pod-security.kubernetes.io/warn": "baseline",
                                "pod-security.kubernetes.io/audit": "restricted"}}}],
        "configmaps.yaml": [{"apiVersion": "v1", "kind": "ConfigMap",
                             "metadata": {"name": "local-access", "labels": labels}, "data": cm}],
        "workloads.yaml": [{"apiVersion": "apps/v1", "kind": "Deployment",
                            "metadata": {"name": "local-access", "labels": labels},
                            "spec": {"replicas": 1, "revisionHistoryLimit": 3,
                                     "strategy": {"type": "Recreate"},  # host ports: never two pods at once
                                     "selector": {"matchLabels": {"app.kubernetes.io/name": "local-access"}},
                                     "template": {"metadata": {"labels": labels, **config_checksum(cm)},
                                                  "spec": {"enableServiceLinks": False, **pod_security({}, "local-access"),
                                                           "containers": [container],
                                                           "volumes": [{"name": "conf", "configMap": {"name": "local-access"}}]}}}}],
        "services.yaml": [{"apiVersion": "v1", "kind": "Service",
                           "metadata": {"name": "local-access", "labels": labels},
                           "spec": {"type": "NodePort", "selector": {"app.kubernetes.io/name": "local-access"},
                                    "ports": nodeports}}],
    }


# ── network policies (ingress) ────────────────────────────────────────────
# One allow-list NetworkPolicy per service (docs/17 "Network policies"): a pod
# becomes isolated once a policy selects it, so services are isolated one by
# one, with no namespace-wide deny that could catch anything else. Egress is
# a follow-up. Kubelet health probes stay allowed (verified on kind).

WATCHERS = ("landing", "uptime-kuma", "nginx-plain")  # health pages, monitors, Browser Hub
SINKS = {"mailpit": 1025, "ntfy": 80}  # delivery ports apps also configure in their own UIs
_ENDPOINT = re.compile(r"(?:^|//|@|\s|=)([a-z][a-z0-9-]+):(\d{2,5})\b")
_OWNERS: dict[str, str] | None = None


def container_owners() -> dict[str, str]:
    """Every in-cluster name (container name, Compose service name) -> service."""
    global _OWNERS
    if _OWNERS is None:
        _OWNERS = {}
        for svc in load_scope().get("ported") or []:
            for n, s in (load_compose(svc).get("services") or {}).items():
                c = re.sub(r"[^a-z0-9-]", "-", (s.get("container_name") or n).lower())
                _OWNERS[c] = svc
                _OWNERS.setdefault(n, svc)
    return _OWNERS


def endpoint_targets(svc: str) -> dict[str, set[int]]:
    """{service: ports} this one connects to by in-cluster name: host:port
    values and HOST/PORT pairs in .env.example, plus Compose environment."""
    owners = container_owners()
    ex = load_env(SERVICES_DIR / svc / ".env.example")
    values = list(ex.values())
    for s in (load_compose(svc).get("services") or {}).values():
        env = s.get("environment") or {}
        values += [str(v) for v in (env.values() if isinstance(env, dict) else env)]
    out: dict[str, set[int]] = {}
    for v in values:
        for host, port in _ENDPOINT.findall(" " + v):
            if host in owners and owners[host] != svc:
                out.setdefault(owners[host], set()).add(int(port))
    for k, v in ex.items():
        if re.search(r"HOST(NAME)?$", k) and v in owners and owners[v] != svc:
            pk = re.sub(r"HOST(NAME)?$", "PORT", k)
            if ex.get(pk, "").isdigit():
                out.setdefault(owners[v], set()).add(int(ex[pk]))
    return out


def web_ports(svc: str) -> set[int]:
    """Ports the router, the localhost proxy and the watchers may use: the
    service's route ports and the container ports Compose publishes."""
    names = {c for c, s in container_owners().items() if s == svc}
    out = {port for c, rs in nginx_routes().items() if c in names for _, port in rs}
    for s in (load_compose(svc).get("services") or {}).values():
        out |= {tgt for _, _, tgt, _ in published_ports(s)}
    if svc == "nginx-plain":
        out.add(80)  # the edge and the Browser Hub
    return out


def network_policy(svc: str) -> dict:
    ported = load_scope().get("ported") or []
    by_ns = lambda ns: {"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": ns}}}  # noqa: E731
    by_svc = lambda s: {"podSelector": {"matchLabels": {"homeserver/service": s}}}  # noqa: E731
    tcp = lambda ports: [{"protocol": "TCP", "port": p} for p in sorted(ports)]  # noqa: E731
    rules: list[dict] = [{"from": [by_svc(svc)]}]  # its own pods: app <-> its database and cache
    web = web_ports(svc)
    if web:
        watchers = [w for w in WATCHERS if w != svc]
        rules.append({"from": [by_ns("infra"), by_ns(LOCAL_ACCESS_NS)] + [by_svc(w) for w in watchers],
                      "ports": tcp(web)})
    for src in sorted(ported):
        ports = endpoint_targets(src).get(svc) if src != svc and svc not in SHARED.values() else None
        if ports:
            rules.append({"from": [by_svc(src)], "ports": tcp(ports)})
    if svc in SHARED.values():
        engine = next(e for e, s in SHARED.items() if s == svc)
        users = sorted(a for a, spec in shared_db_apps().items() if spec["engine"] == engine and a in ported)
        rules.append({"from": [by_svc(a) for a in users], "ports": tcp({5432 if engine == "postgres" else 3306})})
    if svc == "nginx-plain":
        rules.append({"from": [by_svc("cloudflared")], "ports": tcp({80})})  # the tunnel's way in
    has_operator_db = svc in SHARED.values() or any(
        own_postgres(svc, n, s, load_overrides(svc)) or own_mariadb(svc, n, s, load_overrides(svc))
        for n, s in (load_compose(svc).get("services") or {}).items())
    if has_operator_db:  # status checks, replication
        rules.append({"from": [by_ns("cnpg-system"), by_ns("mariadb-operator")]})
    if svc in SINKS:  # apps also set these up in their own UIs: delivery port only
        rules.append({"from": [by_ns(NAMESPACE)], "ports": tcp({SINKS[svc]})})
    return {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
            "metadata": {"name": f"{svc}-ingress", "labels": {"app.kubernetes.io/part-of": "homeserver",
                                                                "homeserver/service": svc}},
            "spec": {"podSelector": {"matchLabels": {"homeserver/service": svc}},
                     "policyTypes": ["Ingress"], "ingress": rules}}


# ── stopped by default (ArgoCD: git = config, k8s.py = on/off) ────────────
# docs/17 "GitOps". apps/<svc> is every service stopped: config, volumes and
# databases exist, nothing runs. The env overlay (envs/<env>/<svc>) switches
# it on when kubernetes/deploy/<env>.yaml lists it (running_patches), so what
# runs is a git change ArgoCD applies, like homeserver.py up/down on Docker.

STOPPED_NODE_SELECTOR = ("homeserver/stopped", "true")  # no node carries it: a DaemonSet's "0 replicas"
CNPG_HIBERNATION = "cnpg.io/hibernation"
# Objects that hold data: never pruned when they leave git, never deleted with
# their Application (ArgoCD sync options); removing data stays a deliberate
# k8s.py/kubectl step, as 'reset' is on Docker.
KEEP_KINDS = {"PersistentVolumeClaim", "PersistentVolume", "Cluster", "MariaDB", "Database", "DatabaseRole",
              "User", "Grant"}
KEEP_OPTIONS = "Prune=false,Delete=false"


def stopped(files: dict[str, list[dict]]) -> None:
    """Mark every workload and database of a service as stopped, in place."""
    for objs in files.values():
        for o in objs:
            k, spec = o["kind"], o.get("spec") or {}
            meta = o["metadata"]
            if k == "Deployment":
                spec["replicas"] = 0
            elif k == "DaemonSet":
                pod = spec["template"]["spec"]
                pod["nodeSelector"] = {**(pod.get("nodeSelector") or {}), STOPPED_NODE_SELECTOR[0]: STOPPED_NODE_SELECTOR[1]}
            elif k == "Job":
                spec["suspend"] = True
            elif k == "Cluster":  # CloudNativePG: initdb once, then hibernate (verified on kind)
                meta["annotations"] = {**(meta.get("annotations") or {}), CNPG_HIBERNATION: "on"}
            elif k == "MariaDB":
                spec["suspend"] = True
            if k in KEEP_KINDS:
                meta["annotations"] = {**(meta.get("annotations") or {}), "argocd.argoproj.io/sync-options": KEEP_OPTIONS}


def running_patches(objs: list[dict]) -> list[dict]:
    """Kustomize patches that undo stopped() for one environment's running
    services: the overlay in envs/<env>/<svc> switches the service on."""
    out = []
    for o in objs:
        k, name = o["kind"], o["metadata"]["name"]
        if k == "Deployment":
            ops = [{"op": "replace", "path": "/spec/replicas", "value": 1}]
        elif k == "DaemonSet":
            ops = [{"op": "remove", "path": "/spec/template/spec/nodeSelector/" + STOPPED_NODE_SELECTOR[0].replace("/", "~1")}]
        elif k in ("Job", "MariaDB"):
            ops = [{"op": "replace", "path": "/spec/suspend", "value": False}]
        elif k == "Cluster":
            ops = [{"op": "remove", "path": "/metadata/annotations/" + CNPG_HIBERNATION.replace("/", "~1")}]
        else:
            continue
        out.append({"target": {"kind": k, "name": name}, "patch": yaml.safe_dump(ops, sort_keys=False)})
    return out


def started(objs: list[dict]) -> list[dict]:
    """The running form of a service's stopped objects (what the overlay's
    patches produce), for cluster.py's smoke tests and imports."""
    import copy
    objs = copy.deepcopy(objs)
    for o in objs:
        k, spec, meta = o["kind"], o.get("spec") or {}, o["metadata"]
        if k == "Deployment":
            spec["replicas"] = 1
        elif k == "DaemonSet":
            (spec["template"]["spec"].get("nodeSelector") or {}).pop(STOPPED_NODE_SELECTOR[0], None)
        elif k in ("Job", "MariaDB"):
            spec["suspend"] = False
        elif k == "Cluster":
            (meta.get("annotations") or {}).pop(CNPG_HIBERNATION, None)
    return objs


