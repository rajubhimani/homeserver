#!/usr/bin/env python3
"""Generate Kubernetes manifests from the Docker Compose definitions.

Compose stays the single source of truth: each services/<svc>/compose.yml
(+ compose.prod.yml), its .env.example, services.json and the nginx-plain
route template are rendered into kubernetes/generated/. Never edit generated
files; edit Compose or kubernetes/overrides/<svc>.yaml and re-run:

    uv run kubernetes/generate.py            # (re)write kubernetes/generated/
    uv run kubernetes/generate.py --check    # exit 1 if generated/ is stale

tests/test_k8s_sync.py runs the --check path, so Compose and Kubernetes can't
drift. Plan and mapping rules: research/kubernetes-compose-parity-plan.md;
step-by-step guide: docs/17-docker-to-kubernetes.md.

Anything the generator can't map safely (a Docker socket, a host path it
doesn't know, a repo folder) raises GenError naming the override to add,
instead of guessing.
"""

